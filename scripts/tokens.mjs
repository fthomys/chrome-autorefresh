// Generates src/ui/tokens.css and src/shared/palette.ts from one seed color.
// Run with `npm run tokens` after changing SEED.
import { writeFileSync } from 'node:fs';
import {
  Hct,
  SchemeTonalSpot,
  MaterialDynamicColors,
  hexFromArgb,
} from '@material/material-color-utilities';

const SEED = '#2b6a5b';

const ROLES = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'surface', 'onSurface', 'onSurfaceVariant',
  'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer',
  'surfaceContainerHigh', 'surfaceContainerHighest',
  'inverseSurface', 'inverseOnSurface', 'inversePrimary',
  'outline', 'outlineVariant', 'scrim',
];

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const colors = new MaterialDynamicColors();

function scheme(isDark) {
  const s = new SchemeTonalSpot(Hct.fromInt(parseInt(SEED.slice(1), 16) | 0xff000000), isDark, 0, '2025');
  return Object.fromEntries(ROLES.map((r) => [r, hexFromArgb(colors[r]().getArgb(s))]));
}

// Damped spring sampled into a CSS linear() easing.
function spring(damping, stiffness) {
  const w0 = Math.sqrt(stiffness);
  const wd = w0 * Math.sqrt(1 - damping * damping);
  const x = (t) =>
    damping >= 1
      ? 1 - Math.exp(-w0 * t) * (1 + w0 * t)
      : 1 - Math.exp(-damping * w0 * t) * (Math.cos(wd * t) + ((damping * w0) / wd) * Math.sin(wd * t));
  let duration = 0.01;
  while (duration < 3 && Math.abs(1 - x(duration)) + Math.abs(x(duration + 0.01) - x(duration)) > 0.001) duration += 0.01;
  const steps = 32;
  const pts = Array.from({ length: steps + 1 }, (_, i) => (i === steps ? 1 : x((duration * i) / steps)).toFixed(4));
  return { easing: `linear(${pts.join(', ')})`, ms: Math.round(duration * 1000) };
}

const light = scheme(false);
const dark = scheme(true);
const block = (s) => Object.entries(s).map(([k, v]) => `  --md-sys-color-${kebab(k)}: ${v};`).join('\n');

// M3 Expressive standard springs (default spatial, fast spatial, fast effects).
const springs = {
  'spatial-default': spring(0.9, 700),
  'spatial-fast': spring(0.9, 1400),
  'effects-fast': spring(1, 3800),
};
const motion = Object.entries(springs)
  .map(([k, v]) => `  --md-sys-motion-${k}: ${v.easing};\n  --md-sys-motion-${k}-duration: ${v.ms}ms;`)
  .join('\n');

writeFileSync(
  new URL('../src/ui/tokens.css', import.meta.url),
  `/* Generated by scripts/tokens.mjs. Do not edit by hand. */
:root {
  color-scheme: light dark;
${block(light)}
${motion}
}

@media (prefers-color-scheme: dark) {
  :root {
${block(dark).replace(/^/gm, '  ')}
  }
}
`,
);

writeFileSync(
  new URL('../src/shared/palette.ts', import.meta.url),
  `// Generated by scripts/tokens.mjs. Do not edit by hand.
// The toolbar badge can't follow the color scheme, so it uses the light palette.
export const BADGE_RUNNING = { background: '${light.primary}', text: '${light.onPrimary}' };
export const BADGE_ATTENTION = { background: '${light.tertiary}', text: '${light.onTertiary}' };
`,
);

console.log('light', light.primary, light.surface, 'dark', dark.primary, dark.surface);
